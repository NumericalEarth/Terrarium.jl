# D1: host-side per-step overhead on CPU (see docs/dev/2026-10/2026-10-17_PLAN_native_vs_reactant_performance_gap.md)
# usage: julia --project=. d1_host_overhead.jl <outfile>
include(joinpath(@__DIR__, "common.jl"))
using Profile
using Oceananigans.TimeSteppers: update_state!

const OUT = ARGS[1]
const CONFIGS = (:land, :land_no_vegetation, :soil_heat)
const NLAT = (2, 4, 8)   # 32, 128, 512 columns

med_ms(b) = median(b).time / 1e6

function phases(integrator, Δt)
    state, model, inputs = integrator.state, integrator.model, integrator.inputs
    grid = get_grid(model)
    ts = Terrarium.get_timestepper(model)
    names = Terrarium.prognostic_names(state)
    return (
        reset_tendencies = () -> Terrarium.reset_tendencies!(state),
        update_inputs = () -> Terrarium.update_inputs!(state, grid, inputs),
        compute_auxiliary = () -> Terrarium.compute_auxiliary!(state, model),
        compute_boundary_conditions = () -> Terrarium.compute_boundary_conditions!(state, model),
        compute_tendencies = () -> Terrarium.compute_tendencies!(state, model),
        explicit_step = () -> Terrarium.explicit_step!(state, grid, ts, Δt, names),
        model_timestep = () -> Terrarium.timestep!(state, model, ts, Δt),
        closure = () -> Terrarium.closure!(state, model),
    )
end

open(OUT, "w") do io
    say(io, "Julia $(VERSION), threads = $(Threads.nthreads()), DEBUG = $(Terrarium.DEBUG[])")

    # 1. whole step vs column count
    say(io, "\n## 1. Whole timestep! (median, evals=1)")
    say(io, "| config | columns | ms/step | allocs/step | KiB/step |")
    say(io, "| --- | --- | --- | --- | --- |")
    fits = Dict{Symbol, Vector{Tuple{Int, Float64}}}()
    for config in CONFIGS, nlat in NLAT
        integrator, Δt = setup(config, CPU(); nlat_half = nlat)
        b = @benchmark timestep!($integrator, $Δt; finalize = false) evals = 1 seconds = 4
        ncol = ncolumns(nlat)
        push!(get!(fits, config, Tuple{Int, Float64}[]), (ncol, med_ms(b)))
        say(io, @sprintf("| %s | %d | %.4g | %d | %.1f |", config, ncol, med_ms(b), b.allocs, b.memory / 1024))
    end
    say(io, "\nLinear fit ms/step = a + b * columns (least squares over 32/128/512):")
    for config in CONFIGS
        x = [Float64(p[1]) for p in fits[config]]
        y = [p[2] for p in fits[config]]
        slope = cov(x, y) / var(x)
        intercept = mean(y) - slope * mean(x)
        say(io, @sprintf("- %s: fixed ≈ %.3f ms/step, per column ≈ %.2f µs", config, intercept, 1e3 * slope))
    end

    # 2. phase breakdown at 32 columns
    say(io, "\n## 2. Phase breakdown at 32 columns (median ms, allocs)")
    for config in CONFIGS
        integrator, Δt = setup(config, CPU(); nlat_half = 2)
        say(io, "\n### $config")
        say(io, "| phase | ms | allocs | KiB |")
        say(io, "| --- | --- | --- | --- |")
        total = 0.0
        for (name, f) in pairs(phases(integrator, Δt))
            f()
            b = @benchmark $f() evals = 1 seconds = 1.5
            total += med_ms(b)
            say(io, @sprintf("| %s | %.4g | %d | %.1f |", name, med_ms(b), b.allocs, b.memory / 1024))
        end
        say(io, @sprintf("| **sum** | %.4g | | |", total))
    end

    # 3. allocation sites, land at 32 columns
    say(io, "\n## 3. Allocation sites, land at 32 columns, one step (top 25 by count)")
    integrator, Δt = setup(:land, CPU(); nlat_half = 2)
    Profile.Allocs.clear()
    Profile.Allocs.@profile sample_rate = 1 timestep!(integrator, Δt; finalize = false)
    allocs = Profile.Allocs.fetch().allocs
    say(io, "total sampled allocations: $(length(allocs))")
    site(a) = begin
        frames = filter(fr -> occursin("Terrarium", string(fr.file)) || occursin("Oceananigans", string(fr.file)), a.stacktrace)
        isempty(frames) ? "(no Terrarium/Oceananigans frame)" : (fr = first(frames); "$(fr.func) @ $(basename(string(fr.file))):$(fr.line)")
    end
    counts = Dict{String, Tuple{Int, Int}}()
    for a in allocs
        k = site(a)
        n, s = get(counts, k, (0, 0))
        counts[k] = (n + 1, s + a.size)
    end
    for (k, (n, s)) in first(sort(collect(counts); by = x -> -x[2][1]), 25)
        say(io, @sprintf("- %5d allocs, %8d B: %s", n, s, k))
    end
    say(io, "\nTypes allocated (top 15):")
    tcounts = Dict{String, Int}()
    for a in allocs
        k = string(a.type)
        k = length(k) > 140 ? k[1:140] * "…" : k
        tcounts[k] = get(tcounts, k, 0) + 1
    end
    for (k, n) in first(sort(collect(tcounts); by = x -> -x[2]), 15)
        say(io, "- $n × $k")
    end

    # 4. sampling profile, land at 32 columns: kernel bodies vs everything else
    say(io, "\n## 4. Sampling profile, land at 32 columns, 400 steps")
    Profile.clear()
    Profile.init(n = 10^7, delay = 0.0005)
    @profile for _ in 1:400
        timestep!(integrator, Δt; finalize = false)
    end
    data, lidict = Profile.retrieve()
    # count samples whose stack contains a KA CPU kernel body (`cpu_` prefixed function generated by @kernel)
    samples = Vector{Vector{UInt64}}()
    cur = UInt64[]
    for ip in data
        if ip == 0
            isempty(cur) || push!(samples, cur)
            cur = UInt64[]
        else
            push!(cur, ip)
        end
    end
    in_kernel = 0
    in_kernel_run = 0
    for s in samples
        names = String[]
        for ip in s
            for fr in get(lidict, ip, Base.StackTraces.StackFrame[])
                push!(names, string(fr.func))
            end
        end
        any(n -> startswith(n, "cpu_"), names) && (in_kernel += 1)
        any(n -> n == "__run" || n == "__thread_run", names) && (in_kernel_run += 1)
    end
    say(io, @sprintf("samples: %d; inside @kernel body (cpu_*): %.1f%%; inside KA __run: %.1f%%",
        length(samples), 100 * in_kernel / max(1, length(samples)), 100 * in_kernel_run / max(1, length(samples))))
    open(OUT * ".flat.txt", "w") do pio
        Profile.print(IOContext(pio, :displaysize => (10000, 400)); format = :flat, sortedby = :count, C = false, mincount = 20)
    end
    say(io, "flat profile written to $(OUT).flat.txt")
end
